const urlCache = new Map();
const mask = new Uint8Array(T * T);

/**
 * Resolves any name (canonical, alias, or garbage) to a canonical icon name.
 * @param {string} name
 * @returns {string}
 */
function resolve(name) {
  const key = typeof name === 'string' ? name.toLowerCase() : '';
  if (DEFS[key]) return key;
  const alias = ICON_ALIASES[key];
  return alias && DEFS[alias] ? alias : 'box';
}

/**
 * @param {string} name
 * @returns {boolean} whether the name (or an alias of it) is a real icon.
 */
export function hasIcon(name) {
  const key = typeof name === 'string' ? name.toLowerCase() : '';
  return !!(DEFS[key] || (ICON_ALIASES[key] && DEFS[ICON_ALIASES[key]]));
}

/** Character at template cell (x, y) after the def's rotation/flip is applied. */
function cellChar(def, x, y) {
  let sx = x;
  let sy = y;
  if (def.flip) sx = T - 1 - sx;
  if (def.rot === 1) { const t = sx; sx = sy; sy = T - 1 - t; }
  else if (def.rot === 2) { sx = T - 1 - sx; sy = T - 1 - sy; }
  else if (def.rot === 3) { const t = sx; sx = T - 1 - sy; sy = t; }
  const row = def.rows[sy];
  return row && sx < row.length ? row[sx] : '.';
}

/** Paints a definition into the painter at a 1px inset and outlines it. */
function paintIcon(p, def) {
  const shades = ramp(def.c, 5);
  const shadow = shades[1];
  const base = shades[2];
  const light = shades[3];
  const dark = outlineColor(def.c);
  for (let y = 0; y < T; y++) for (let x = 0; x < T; x++) mask[y * T + x] = cellChar(def, x, y) === '.' ? 0 : 1;
  const on = (x, y) => x >= 0 && y >= 0 && x < T && y < T && mask[y * T + x] === 1;
  for (let y = 0; y < T; y++) {
    for (let x = 0; x < T; x++) {
      const ch = cellChar(def, x, y);
      if (ch === '.') continue;
      let col;
      if (ch === '#') {
        if (!on(x, y - 1)) col = light;
        else if (!on(x, y + 1)) col = shadow;
        else if (!on(x - 1, y)) col = light;
        else if (!on(x + 1, y)) col = shadow;
        else col = base;
      } else if (ch === '1') col = shadow;
      else if (ch === '2') col = base;
      else if (ch === '3') col = light;
      else if (ch === '0') col = dark;
      else col = FIXED[ch] || base;
      p.set(x + 1, y + 1, col);
    }
  }
  p.outline(dark);
}

/**
 * The 16×16 unit sprite of an icon (cached). Unknown names return the generic box.
 * @param {string} name
 * @returns {object} spr
 */
export function iconSprite(name) {
  const key = resolve(name);
  return cached('icon:' + key, () => makeSprite(ICON_SIZE, ICON_SIZE, (p) => paintIcon(p, DEFS[key]), { ox: 0, oy: 0 }));
}

/**
 * PNG data URL of an icon, upscaled with nearest-neighbour sampling. The
 * intrinsic size is the next multiple of 16 ≥ size; set the display size in CSS.
 * Never throws; returns '' only when no DOM canvas exists.
 * @param {string} name
 * @param {number} [size]
 * @returns {string}
 */
export function icon(name, size) {
  const key = resolve(name);
  const px = size >= 1 && Number.isFinite(size) ? size : ICON_SIZE;
  const scale = Math.max(1, Math.ceil(px / ICON_SIZE));
  const cacheKey = key + '@' + scale;
  const hit = urlCache.get(cacheKey);
  if (hit !== undefined) return hit;
  let url = '';
  try {
    url = toDataURL(iconSprite(key), scale);
  } catch (e) {
    url = '';
  }
  urlCache.set(cacheKey, url);
  return url;
}
