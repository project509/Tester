/**
 * art/icons.js — Procedural 16×16 pixel icons for the DOM UI and HUD.
 *
 * Every icon is a 14×14 template of characters painted into a 16×16 sprite.
 * `#` pixels are auto-bevelled (top/left edges light, bottom/right edges
 * shadow, interior base) in the icon's own colour; letter codes pin fixed
 * palette colours (paper, ink, blood, amber, skin, rot, wood, steel…). A 1px
 * dark outline is added last so icons read on any background. Sprites and
 * data URLs are cached; unknown names fall back to a generic box.
 *
 * Public API:
 *   ICONS                       canonical icon names
 *   ICON_ALIASES                { alias: canonicalName }
 *   ICON_SIZE                   16
 *   icon(name, size=16) → dataURL   (nearest-neighbour; sizes that are not a
 *                                    multiple of 16 get the next multiple — size via CSS)
 *   iconSprite(name) → spr       16×16 unit sprite for canvas drawing
 *   hasIcon(name) → boolean
 */

